def build_parser() -> argparse.ArgumentParser:
    """Return an isolated parser copy from the cached immutable grammar."""
    return copy.deepcopy(_build_parser_template())


def dispatch_parser() -> argparse.ArgumentParser:
    """Return a per-thread parser copy for the read-only runtime dispatcher."""
    parser = getattr(_DISPATCH_PARSERS, 'parser', None)
    if parser is None:
        parser = copy.deepcopy(_build_parser_template())
        _DISPATCH_PARSERS.parser = parser
    return parser
